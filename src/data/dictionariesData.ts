// 根据角色类型快速获取其拥有的权限列表
export function getDefaultPermissionsByRole(role: string): string[] {
  if (role === 'superAdmin') {
    return ALL_SYSTEM_PERMISSIONS.map((p) => p.id);
  }
  if (role === 'admin') {
    // 管理员：除系统设置 (config.edit) 和 账号权限分配 (admins.manage) 之外的全部
    return ALL_SYSTEM_PERMISSIONS.filter((p) => p.id !== 'config.edit' && p.id !== 'admins.manage').map(
      (p) => p.id
    );
  }
  if (role === 'operations') {
    // 运营员：与活动、赛事、订单、会员、积分商城、评价、商户、营销等相关
    return [
      'stats.view',
      'activities.view',
      'activities.create',
      'activities.edit',
      'activities.delete',
      'events.view',
      'events.edit',
      'orders.view',
      'orders.refund',
      'members.view',
      'members.points',
      'free.view',
      'free.edit',
      'mall.view',
      'mall.ship',
      'reviews.audit',
      'wishes.audit',
      'merchants.audit',
      'chatlogs.view',
      'knowledge.edit',
      'news.edit',
      'dictionaries.manage',
    ];
  }
  if (role === 'operator') {
    // 操作员：默认具备活动录入发布与查看权限，可单独打勾微调
    return ['activities.view', 'activities.create', 'activities.edit'];
  }
  return ['activities.view'];
}
